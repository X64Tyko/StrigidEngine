static const char* FieldTypeNames[] = {
	"float", "int32_t", "uint32_t", "bool", "Fixed32",
};
static constexpr int NumFieldTypes = 5;

static const char* TierMacros[] = {
	"TNX_TEMPORAL_FIELDS",
	"TNX_VOLATILE_FIELDS",
	"TNX_REGISTER_FIELDS",
};
static const char* TierNames[] = { "Temporal", "Volatile", "Cold" };
static constexpr int NumTiers  = 3;

static const char* GroupNames[] = { "Render", "Physics", "Logic", "Dual" };
static constexpr int NumGroups  = 4;

// ScriptFieldType and SystemID ordinals match the index arrays above.
static const ScriptFieldType TypeIndexToScript[] = {
	ScriptFieldType::Float, ScriptFieldType::Int32, ScriptFieldType::UInt32,
	ScriptFieldType::Bool,  ScriptFieldType::Fixed32,
};
static const SystemID GroupIndexToSysID[] = {
	SystemID::Render, SystemID::Physics, SystemID::Logic, SystemID::Dual,
};
static const CacheTier TierIndexToCacheTier[] = {
	CacheTier::Temporal, CacheTier::Volatile, CacheTier::Volatile, // Cold → Volatile for script
};

